import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read=(p)=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const pricing=read("src/app/pricing/page.tsx");
const languages=read("src/app/languages/page.tsx");
const purchase=read("src/components/PurchasePackages.tsx");
const selector=read("src/components/LanguageSelector.tsx");
const nav=read("src/components/Navbar.tsx");
const contact=read("src/app/contact/page.tsx");
const testimonials=read("src/components/TestimonialsSection.tsx");
const publicTestimonials=read("src/data/public-testimonials.ts");
const sitemap=read("src/app/sitemap.ts");
const robots=read("src/app/robots.ts");
const packagePage=read("src/app/(portal)/packages/page.tsx");
const checkout=read("src/app/(portal)/packages/actions.ts");
const returnPage=read("src/app/(portal)/packages/return/page.tsx");
const setup=read("src/app/(portal)/dashboard/setup/page.tsx");
const onboarding=read("src/app/onboarding/OnboardingForm.tsx");

assert.ok(pricing.includes("Choose a language. Choose a package. Pay online."));
assert.ok(pricing.includes("<PurchaseJourney"));
assert.ok(languages.includes("Start by choosing your language."));
assert.ok(purchase.includes('name') || purchase.includes("selectedLanguage"));
assert.ok(purchase.includes("Choose a language first"));
assert.ok(purchase.includes("Pay online"));
assert.equal(purchase.includes("I have a question"),false);
assert.ok(selector.includes("/pricing?language="),"language cards must lead directly to pricing with language context");
assert.ok(nav.includes("${prefix}/pricing") && nav.includes("${prefix}/languages"));
assert.ok(nav.includes("${prefix}/companies"),"companies must have their own localized top-level treatment");
assert.equal(contact.includes("Message us on Instagram"),false,"Instagram must not compete with payment");
assert.equal(publicTestimonials.includes('quote: "'),false,"do not publish fabricated testimonials");
assert.ok(testimonials.includes("These are not reviews or fabricated quotes"),"empty testimonial state must be transparent");
assert.ok(sitemap.includes('/pricing') && sitemap.includes('/languages'));
assert.ok(robots.includes('"/pricing"') && robots.includes('"/languages"'));
assert.ok(packagePage.includes("selectedLanguage"));
assert.ok(checkout.includes("learning_language"));
assert.ok(checkout.includes("success_url") && checkout.includes("language="));
assert.ok(returnPage.includes("dashboard/setup?payment=success"));
assert.ok(setup.includes("initialLanguage"));
assert.ok(onboarding.includes("initialStudentLanguage"));
console.log("PASS: language-to-payment conversion, company navigation, honest social proof and SEO routes");
