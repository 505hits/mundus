import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read=(p)=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const layout=read("src/app/layout.tsx");
const manager=read("src/components/AnalyticsManager.tsx");
const banner=read("src/components/AnalyticsConsentBanner.tsx");
const settings=read("src/components/AnalyticsConsentSettings.tsx");
const cookies=read("src/app/cookies/page.tsx");
const languages=read("src/components/LanguageSelector.tsx");
const pricing=read("src/components/PurchasePackages.tsx");
assert.ok(layout.includes("<AnalyticsManager") && layout.includes("<AnalyticsConsentBanner"));
assert.ok(layout.includes("NEXT_PUBLIC_GA_MEASUREMENT_ID") === false,"public GA ID belongs in analytics manager, not metadata");
assert.ok(layout.includes("GOOGLE_SITE_VERIFICATION") && layout.includes("BING_SITE_VERIFICATION"));
assert.ok(manager.includes("NEXT_PUBLIC_GA_MEASUREMENT_ID") && manager.includes("NEXT_PUBLIC_CLARITY_PROJECT_ID"));
assert.ok(manager.includes('consent!=="granted"'),"analytics scripts must require consent");
assert.ok(manager.includes("googletagmanager.com/gtag/js") && manager.includes("clarity.ms/tag"));
assert.ok(manager.includes("initialPageViewHandled") && manager.includes("send_page_view: true"),"GA4 should let config own the initial page view and only emit route-change page views afterward");
assert.ok(banner.includes("Necessary only") && banner.includes("Allow analytics"));
assert.ok(settings.includes("Disable analytics"));
assert.ok(cookies.includes("Google Analytics 4") && cookies.includes("Microsoft Clarity"));
assert.ok(languages.includes('trackEvent("select_language"'));
assert.ok(pricing.includes('trackEvent("select_lesson_duration"') && pricing.includes('trackEvent("select_package"'));
console.log("PASS: consent-controlled analytics, webmaster verification and conversion events are wired");